"""Write docs/RULES.md: every rule with its severity and message (rules from config.json "messages" + text_fixes;
severity read from engine/rules.py / engine/rules_net.py next to the rule key).

  python tools/rules_doc.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
cfg = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))
SRC = {m: (ROOT / "engine" / m).read_text(encoding="utf-8") for m in ("rules.py", "rules_net.py")}
ORDER = ["ERROR", "WARNING", "MINOR", "INFO"]


def severity(key: str) -> tuple[list, str]:
    for mod, src in SRC.items():
        i = src.find(f'"{key}"')
        if i < 0:
            continue
        tail = src[i:i + 1000]
        both = re.match(r'"[A-Z_]+"[^"]*"(ERROR)" if near else "(WARNING)"', tail)
        if both:
            return ["ERROR", "WARNING"], mod
        m = re.search(r'"(ERROR|WARNING|MINOR|INFO)"', tail)
        return ([m[1]] if m else ["?"]), mod
    return ["?"], "?"


fixes = {fx["id"]: fx.get("severity", "MINOR") for fx in cfg["text_fixes"]}
rows = []
for key, msg in cfg["messages"].items():
    sev, mod = ([fixes[key]], "config.json") if key in fixes else severity(key)
    note = msg.get("note_en", "")
    rows.append((mod, key, sev, msg.get("en", ""), note))
rows.sort(key=lambda r: (r[0] != "rules_net.py", r[1]))
lines = ["# LDV check rules", "",
         "Generated by `tools/rules_doc.py` from `config.json` and `engine/rules*.py` — do not edit by hand. "
         "Messages in English (Vietnamese in config.json); `{…}` is filled in per finding.", "",
         f"{len(rows)} rules, {sum(r[0] == 'rules_net.py' for r in rows)} of them new in 2.1. "
         "ERROR = must be fixed · WARNING = a person must verify · MINOR = small inconsistency · INFO = information.", "",
         "| Rule | Severity | New | Message — _note_ |", "|---|---|---|---|"]
for mod, key, sev, en, note in rows:
    lines.append(f"| `{key}` | {' / '.join(sev)} | {'2.1' if mod == 'rules_net.py' else ''} | "
                 f"{en.replace('|', '/')}" + (f" — _{note.replace('|', '/')}_" if note else "") + " |")
(ROOT / "docs" / "RULES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"docs/RULES.md: {len(rows)} rules, {sum(r[0] == 'rules_net.py' for r in rows)} new; unknown severity:",
      [r[1] for r in rows if r[2] == ['?']])
